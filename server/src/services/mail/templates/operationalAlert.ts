/**
 * The operational-alert email body (AI-34).
 *
 * This is the mail the model-health watchdog sends when a configured model becomes
 * unavailable or starts degrading, and when it recovers. It is a pure function of its
 * inputs: no I/O, no clock, no environment, no network, and no knowledge of which model
 * tripped it. The caller owns the decision and the wording; this renderer only presents
 * the subject and text it is handed.
 *
 * NOTHING SECRET MAY REACH IT. An alert names model ids, endpoint status codes and uptime
 * percentages — operational facts an operator needs — and never an API key, a base URL, a
 * tenant, a user or a business id. The watchdog builds that text; this module does not add
 * anything to it.
 *
 * The HTML is deliberately plain, and every interpolated string is escaped. The text is
 * the authoritative body: a mail client that refuses HTML still shows the whole report,
 * which matters for an alert whose only job is to be read at an inconvenient hour.
 */

function normaliseRequired(value: unknown, name: string) {
  const raw = typeof value === 'string' ? value.trim() : '';
  if (!raw) throw new Error(`operationalAlertEmail requires a non-empty ${name}.`);
  return raw;
}

function normaliseAppName(appName: string | undefined) {
  const raw = typeof appName === 'string' ? appName.trim() : '';
  return raw || 'Inventory AI';
}

function escapeHtml(value: string) {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

/**
 * Renders one operational alert.
 *
 * The subject is passed through unchanged because the watchdog has already built the
 * operator-facing sentence (it knows whether this is a degradation, an outage or a
 * recovery). The body is preserved verbatim in a `<pre>` so the aligned endpoint report
 * survives in the mail client.
 */
export function operationalAlertEmail({
  subject,
  text,
  appName,
}: {
  subject: string;
  text: string;
  appName?: string;
}) {
  const safeSubject = normaliseRequired(subject, 'subject');
  const safeText = normaliseRequired(text, 'text');
  const name = normaliseAppName(appName);

  return {
    subject: safeSubject,
    text: safeText,
    html: [
      '<!doctype html>',
      '<html>',
      '<body style="font-family: -apple-system, Segoe UI, Roboto, Helvetica, Arial, sans-serif; color: #1f2937;">',
      `<h2 style="margin: 0 0 12px;">${escapeHtml(name)} — assistant health</h2>`,
      `<pre style="white-space: pre-wrap; font-size: 14px; line-height: 1.5; background: #f8fafc; border: 1px solid #e2e8f0; border-radius: 6px; padding: 12px;">${escapeHtml(safeText)}</pre>`,
      '<p style="font-size: 12px; color: #64748b; margin: 16px 0 0;">',
      'This message is generated by the scheduled model-health check. It is sent only when the state changes.',
      '</p>',
      '</body>',
      '</html>',
    ].join('\n'),
  };
}

export default { operationalAlertEmail };
